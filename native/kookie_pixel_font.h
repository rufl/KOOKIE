static inline int kookie_pixel_glyph_for_ascii(unsigned char value) {
    if (value >= 'A' && value <= 'Z') return (int)(value - 'A') + 1;
    if (value >= 'a' && value <= 'z') return (int)(value - 'a') + 1;
    if (value >= '0' && value <= '9') return (int)(value - '0') + 27;
    switch (value) {
        case '.': return 37;
        case ':': return 38;
        case '-': return 39;
        case '/': return 40;
        case '%': return 41;
        case '>': return 42;
        case '+': return 43;
        case '?': return 44;
        default: return 0;
    }
}

